package de.anton.wannpasstes;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Primary;
import org.springframework.context.ConfigurableApplicationContext;

import java.nio.file.Path;
import java.sql.DriverManager;

import static org.junit.jupiter.api.Assertions.*;

class ProfileDatabaseUpgradeTests {

    @TempDir
    Path databaseDirectory;

    @Test
    void preservesLegacyProfilesAndPersistsEditsAcrossRestart() throws Exception {
        String url = "jdbc:h2:file:" + databaseDirectory.resolve("legacy") + ";DB_CLOSE_ON_EXIT=FALSE";
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE search_profiles (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL,
                        location_id INTEGER NOT NULL,
                        activity ENUM ('CYCLING','HIKING','RUNNING','WALKING') NOT NULL,
                        min_duration_minutes INTEGER NOT NULL,
                        temperature_preference ENUM ('ANY','COOL','MILD','WARM') NOT NULL,
                        wind_preference ENUM ('ANY','MODERATE','WEAK') NOT NULL,
                        precipitation_preference ENUM ('ANY','DRY','LIGHT_DRIZZLE','LIGHT_RAIN') NOT NULL
                    )
                    """);
            statement.executeUpdate("""
                    INSERT INTO search_profiles
                        (name, location_id, activity, min_duration_minutes, temperature_preference, wind_preference,
                         precipitation_preference)
                    VALUES ('Altprofil', 123, 'WALKING', 60, 'MILD', 'WEAK', 'DRY'),
                           ('altprofil', 456, 'HIKING', 120, 'COOL', 'MODERATE', 'LIGHT_RAIN'),
                           ('altprofil (2)', 789, 'HIKING', 60, 'COOL', 'MODERATE', 'DRY')
                    """);
        }

        long editedId;
        try (var application = startApplication(url)) {
            var repository = application.getBean(SearchProfileRepository.class);
            var profiles = application.getBean(SearchProfileService.class);
            assertEquals(3, repository.count());
            SearchProfile existing = repository.findAll().stream()
                    .filter(profile -> profile.getLocationId() == 123).findFirst().orElseThrow();
            assertNull(existing.getLocationName());
            assertEquals("Altprofil", existing.getName());
            assertEquals("altprofil (3)", repository.findByNameKey("altprofil (3)").orElseThrow().getName());
            assertEquals(789, repository.findByNameKey("altprofil (2)").orElseThrow().getLocationId());
            assertFalse(repository.existsByNameKeyIsNull());
            editedId = existing.getId();

            assertThrows(SearchProfileService.InvalidProfile.class, () -> profiles.save(null, form(" ALTPROFIL ")));
            profiles.save(editedId, form("Neuer Name"));
        }

        try (var application = startApplication(url)) {
            var repository = application.getBean(SearchProfileRepository.class);
            assertEquals(3, repository.count());
            SearchProfile updated = repository.findById(editedId).orElseThrow();
            assertEquals("Neuer Name", updated.getName());
            assertEquals("Synthetischer Ort", updated.getLocationName());
            assertEquals(150, updated.getMinDurationMinutes());
        }
    }

    private ProfileForm form(String name) {
        return new ProfileForm(name, 123, Activity.CYCLING, 150, TemperaturePreference.WARM,
                WindPreference.WEAK, PrecipitationPreference.DRY);
    }

    private ConfigurableApplicationContext startApplication(String url) {
        return new SpringApplicationBuilder(WannPasstEsApplication.class, TestLocations.class)
                .web(WebApplicationType.NONE)
                .run("--spring.datasource.url=" + url, "--spring.jpa.hibernate.ddl-auto=update");
    }

    @TestConfiguration
    static class TestLocations {

        @Bean
        @Primary
        GeocodingClient testGeocodingClient() {
            return new GeocodingClient() {
                @Override
                public GeocodingResponse.Location getLocation(int id) {
                    return new GeocodingResponse.Location(id, "Synthetischer Ort", 52.5, 13.4,
                            "Europe/Berlin", null, null);
                }
            };
        }
    }
}
