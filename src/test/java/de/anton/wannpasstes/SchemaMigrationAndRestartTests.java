package de.anton.wannpasstes;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

import static org.hamcrest.Matchers.allOf;
import static org.hamcrest.Matchers.containsString;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.redirectedUrl;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * An existing file database from the first version (without the
 * {@code location_name} column) keeps its profiles, and edited profiles
 * survive a restart of the application (A2, A7).
 */
class SchemaMigrationAndRestartTests {

    @TempDir
    private Path directory;

    private ConfigurableApplicationContext start(String url) {
        // Command line arguments take precedence over the test application.properties.
        return new SpringApplicationBuilder(WannPasstEsApplication.class).run(
                "--spring.datasource.url=" + url,
                "--spring.jpa.hibernate.ddl-auto=update",
                "--server.port=0",
                "--spring.main.banner-mode=off");
    }

    @Test
    void keepsLegacyProfilesAndPersistsEditsAcrossRestarts() throws Exception {
        String url = "jdbc:h2:file:" + directory.resolve("legacy-db") + ";DB_CLOSE_ON_EXIT=FALSE";

        // Schema and data as written by the first version of the application.
        try (Connection connection = DriverManager.getConnection(url, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    create table search_profiles (
                        id bigint generated by default as identity primary key,
                        activity varchar(255) not null,
                        location_id integer not null,
                        min_duration_minutes integer not null,
                        name varchar(100) not null,
                        precipitation_preference varchar(255) not null,
                        temperature_preference varchar(255) not null,
                        wind_preference varchar(255) not null)
                    """);
            statement.execute("""
                    insert into search_profiles (activity, location_id, min_duration_minutes, name,
                        precipitation_preference, temperature_preference, wind_preference)
                    values ('WALKING', 2950159, 60, 'Legacy walk', 'DRY', 'MILD', 'WEAK')
                    """);
        }

        long id;
        try (ConfigurableApplicationContext context = start(url)) {
            SearchProfileRepository repository = context.getBean(SearchProfileRepository.class);
            SearchProfile legacy = repository.findAll().getFirst();
            id = legacy.getId();
            assertEquals("Legacy walk", legacy.getName());
            assertNull(legacy.getLocationName());

            MockMvc mvc = MockMvcBuilders.webAppContextSetup((WebApplicationContext) context).build();
            mvc.perform(get("/profiles"))
                    .andExpect(status().isOk())
                    .andExpect(content().string(allOf(
                            containsString("Legacy walk"),
                            containsString("Unbekannter Ort (ID 2950159)"))));

            mvc.perform(post("/profiles/" + id + "/edit")
                            .param("profileName", "Renamed walk")
                            .param("locationId", "2852458")
                            .param("locationName", "Potsdam")
                            .param("activity", "HIKING")
                            .param("minDurationMinutes", "45")
                            .param("temperaturePreference", "COOL")
                            .param("windPreference", "MODERATE")
                            .param("precipitationPreference", "LIGHT_RAIN"))
                    .andExpect(status().is3xxRedirection())
                    .andExpect(redirectedUrl("/profiles"));
        }

        try (ConfigurableApplicationContext context = start(url)) {
            SearchProfile reloaded = context.getBean(SearchProfileRepository.class).findById(id).orElseThrow();
            assertEquals("Renamed walk", reloaded.getName());
            assertEquals(2852458, reloaded.getLocationId());
            assertEquals("Potsdam", reloaded.getLocationName());
            assertEquals(Activity.HIKING, reloaded.getActivity());
            assertEquals(45, reloaded.getMinDurationMinutes());
            assertEquals(TemperaturePreference.COOL, reloaded.getTemperaturePreference());
            assertEquals(WindPreference.MODERATE, reloaded.getWindPreference());
            assertEquals(PrecipitationPreference.LIGHT_RAIN, reloaded.getPrecipitationPreference());
        }
    }
}
